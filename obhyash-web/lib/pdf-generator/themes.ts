// Hash function to deterministically map any text to a number
function hashString(str: string): number {
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  return Math.abs(hash);
}

/**
 * Returns a theme from the 100+ curated palette library.
 * - If themeKey matches a specific theme, it is returned.
 * - If themeKey is 'random' or unspecified, it picks randomly.
 * - If seed is provided, it picks deterministically from the 100+ themes so the same exam keeps its unique theme.
 * - If categoryFilter is provided (medical / engineering / varsity), it prioritizes themes in that vibe.
 */
export function getCuratedTheme(
  themeKey?: string,
  seed?: string,
  categoryFilter?: string
): ThemeColors {
  if (themeKey && themeKey !== 'random' && themeKey !== 'auto' && ALL_THEMES[themeKey]) {
    return ALL_THEMES[themeKey];
  }

  let pool = THEME_KEYS;
  if (categoryFilter) {
    const cat = categoryFilter.toLowerCase();
    const filtered = THEME_KEYS.filter(k => {
      const fam = ALL_THEMES[k].categoryFamily;
      if (cat.includes('med') && fam === 'medical') return true;
      if (cat.includes('eng') && fam === 'engineering') return true;
      if (cat.includes('var') && fam === 'varsity') return true;
      return false;
    });
    if (filtered.length > 0) {
      pool = filtered;
    }
  }

  // If explicitly 'random', pick truly randomly
  if (themeKey === 'random') {
    const randomIdx = Math.floor(Math.random() * pool.length);
    return ALL_THEMES[pool[randomIdx]];
  }

  // If seed provided, hash deterministically
  if (seed && seed.trim()) {
    const idx = hashString(seed) % pool.length;
    return ALL_THEMES[pool[idx]];
  }

  const randomIdx = Math.floor(Math.random() * pool.length);
  return ALL_THEMES[pool[randomIdx]];
}
